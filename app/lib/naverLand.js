// 네이버 부동산(m.land) 단지 검색 딥링크. 단지 고정 URL은 비공개라 검색어로 best-effort.
// 검색이 단지를 찾으면 네이버가 단지 상세페이지로 리다이렉트한다 — 그게 성공 판정 기준.
//
// ⚠️ 국토부 단지명은 네이버 표기와 자주 다르다("공작아파트"↔"공작부영아파트",
// "삼성래미안"↔"비산삼성래미안아파트"). 그래서 **카카오가 아는 정식 단지명(canonical)을
// 최우선으로 쓴다** — 지오코딩할 때 이미 받아오는 값이라 추가 호출이 없다.
// 2026-07-29 안양 동안구 30곳 실측: 국토부명 21/30(70%) → 카카오 정식명+동 24/30(80%).
// 같은 표본에서 카카오 정식명이 이기거나 비겼고 진 경우는 없었다.
//
// canonical이 없을 때(카카오가 아파트로 확인해주지 못한 단지)는 기존 괄호 처리 규칙을 쓴다:
// ① 괄호 안이 동·필지번호(숫자/영문/쉼표·하이픈뿐 or "제N(상가)동")면 **통째로 제거** —
//   네이버가 모르는 토큰이라 넣으면 0건, 빼면 정확 매칭(2026-07-05 실측: 한미(A1,A2,B)·
//   트윈팰리스(101동)·대아(제101상가동) 단지 페이지 복구).
// ② 한글이 든 괄호는 **공백으로 풀어 유지** — 단지 구분자라 빼면 오히려 0건(2026-06-30 실측:
//   동편마을(3단지)·한가람(두산) 등은 내용 포함해야 정확 매칭).
export function naverLandUrl(umdNm, aptNm, canonicalName) {
  const cleaned =
    canonicalName ||
    aptNm.replace(/\(([^)]*)\)/g, (_, inner) =>
      /^[0-9A-Za-z.,\-\s]*$/.test(inner) || /^제?\d+(상가)?동$/.test(inner) ? " " : ` ${inner} `
    );
  const q = `${umdNm} ${cleaned}`.replace(/[()]/g, " ").replace(/\s+/g, " ").trim();
  return `https://m.land.naver.com/search/result/${encodeURIComponent(q)}`;
}
